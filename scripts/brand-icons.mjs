// Everything brand-related is derived from the MASTER logo, public/brand/sa-logo.svg
// (the client's traced logo; backup in client-assets/brand/). Never recolour or redraw it.
//   node scripts/brand-icons.mjs
// writes:
//   src/components/ui/logoMark.js   path + dot + original colours (inlined in the UI)
//   public/favicon.svg              SVG favicon (mark on a light tile)
//   public/favicon-32.png, public/apple-touch-icon.png (180), public/icon-512.png
import fs from 'node:fs'
import sharp from 'sharp'

const MASTER = 'public/brand/sa-logo.svg'
const PAPER = '#F6F4EF' // light background only: the mark is black

const src = fs.readFileSync(MASTER, 'utf8').replace(/<metadata>[\s\S]*?<\/metadata>/, '')
const viewBox = src.match(/viewBox="([^"]+)"/)[1]
const path = src.match(/<path([^>]*)\/?>/)[1]
const circle = src.match(/<circle([^>]*)\/?>/)[1]
const attr = (s, n) => s.match(new RegExp(`\\s${n}="([^"]+)"`))[1]
const mark = {
  viewBox,
  d: attr(path, 'd'),
  ink: attr(path, 'fill'),
  dot: { cx: +attr(circle, 'cx'), cy: +attr(circle, 'cy'), r: +attr(circle, 'r'), fill: attr(circle, 'fill') },
}
const [x, y, w, h] = viewBox.split(/\s+/).map(Number)
mark.clearSpace = +((2 * mark.dot.r) / h).toFixed(4) // dot diameter as a fraction of the mark's height

fs.writeFileSync(
  'src/components/ui/logoMark.js',
  `// GENERATED by scripts/brand-icons.mjs from public/brand/sa-logo.svg (the master logo).
// Do not edit by hand, recolour or redraw. Colours are the original ones.
export const MARK = ${JSON.stringify(mark, null, 2)}
`,
)

/** Square icon: mark centred on a light tile; `pad` = clear space as a fraction of the tile. */
const icon = (pad, radius = 0) => {
  const side = Math.max(w, h) / (1 - 2 * pad)
  const ox = x - (side - w) / 2
  const oy = y - (side - h) / 2
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ox.toFixed(2)} ${oy.toFixed(2)} ${side.toFixed(2)} ${side.toFixed(2)}"><rect x="${ox.toFixed(2)}" y="${oy.toFixed(2)}" width="${side.toFixed(2)}" height="${side.toFixed(2)}" rx="${(side * radius).toFixed(2)}" fill="${PAPER}"/><path fill="${mark.ink}" d="${mark.d}"/><circle fill="${mark.dot.fill}" cx="${mark.dot.cx}" cy="${mark.dot.cy}" r="${mark.dot.r}"/></svg>`
}

// favicons: clear space ≥ the dot's diameter around the mark (pad ≥ clearSpace × h / side)
fs.writeFileSync('public/favicon.svg', icon(0.1, 0.18))
await sharp(Buffer.from(icon(0.1, 0.18)), { density: 300 }).resize(32, 32).png().toFile('public/favicon-32.png')
await sharp(Buffer.from(icon(0.16)), { density: 300 }).resize(180, 180).png().toFile('public/apple-touch-icon.png')
await sharp(Buffer.from(icon(0.18)), { density: 300 }).resize(512, 512).png().toFile('public/icon-512.png')
console.log('logoMark.js, favicon.svg, favicon-32.png, apple-touch-icon.png, icon-512.png written')
