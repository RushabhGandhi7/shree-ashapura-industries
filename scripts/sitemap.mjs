// Writes dist/sitemap.xml and dist/robots.txt from the route list (src/routes.js).
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const { pages, SITE } = await import(pathToFileURL(path.resolve('src/routes.js')).href)
const today = new Date().toISOString().slice(0, 10)
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;')

const urls = pages
  .map(
    (p) => `  <url>
    <loc>${SITE}${p.path === '/' ? '/' : p.path}</loc>
    <lastmod>${today}</lastmod>
    <priority>${p.priority ?? 0.5}</priority>
    <image:image><image:loc>${SITE}${p.image}</image:loc><image:title>${esc(p.title)}</image:title></image:image>
  </url>`,
  )
  .join('\n')

fs.writeFileSync(
  path.resolve('dist/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/sitemap.mjs from src/routes.js. Domain: SITE_URL (VITE_SITE_URL, src/config.js). -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls}
</urlset>
`,
)
fs.writeFileSync(
  path.resolve('dist/robots.txt'),
  `# Generated by scripts/sitemap.mjs
User-agent: *
Allow: /
Disallow: /lab

Sitemap: ${SITE}/sitemap.xml
`,
)
console.log(`sitemap.xml: ${pages.length} URLs · robots.txt written`)
